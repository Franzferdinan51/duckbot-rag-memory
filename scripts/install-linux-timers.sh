#!/usr/bin/env bash
# scripts/install-linux-timers.sh — install the DuckBot maintenance timers as
# systemd user units (daily decay prune + weekly FSRS tuning).
#
# duckbot-secret-scan: allowlist-file
#
# Companion to scripts/install-linux.sh. The watcher daemon is already covered
# there; this one installs the *scheduled maintenance* jobs that INSTALL.md
# recommends but previously had no Linux setup script for. Purely additive:
# it writes unit files and enables timers, touching nothing else.
#
# What it does:
#   1. Writes ~/.config/systemd/user/duckbot-decay.{service,timer}
#   2. Writes ~/.config/systemd/user/duckbot-fsrs.{service,timer}
#   3. Reloads systemd, enables + starts both timers
#   4. Enables linger so the timers survive logout (requires sudo, one-time)
#
# Requirements:
#   - Linux (any distro with systemd)
#   - loginctl enable-linger $USER (one-time; requires sudo)
#   - The venv at $REPO_ROOT/.venv (run scripts/install.sh first)
#
# Usage (from repo root):
#   ./scripts/install-linux-timers.sh
#
# Manage with:
#   systemctl --user list-timers 'duckbot*'
#   systemctl --user duckbot-decay.service        # run decay now
#   systemctl --user duckbot-fsrs.service          # run FSRS tuning now
#   journalctl --user -u duckbot-decay -f

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$REPO_ROOT"

# Make shell + helper scripts executable. The `*.sh` glob misses
# `duckbot-ask` (no extension) and the Python helpers, so chmod them
# explicitly. Silently ignore if not present.
chmod +x scripts/*.sh scripts/duckbot-ask 2>/dev/null || true
chmod +x scripts/_format_*.py 2>/dev/null || true

if [[ "$(uname -s 2>/dev/null || echo unknown)" != "Linux" ]]; then
  echo "❌ install-linux-timers.sh: this is for Linux only. Detected: $(uname -s)" >&2
  exit 1
fi

# 1. Validate venv
if [[ ! -x .venv/bin/python ]]; then
  echo "❌ .venv/bin/python not found. Run scripts/install.sh first." >&2
  exit 1
fi

PYTHON_BIN="$REPO_ROOT/.venv/bin/python"
UNIT_DIR="$HOME/.config/systemd/user"
LOG_DIR="$REPO_ROOT/data/logs"
mkdir -p "$UNIT_DIR" "$LOG_DIR"

# 2. Write the decay service + timer (daily at 03:00, prunes memories below
#    the retention floor).
cat > "$UNIT_DIR/duckbot-decay.service" <<EOF
# duckbot-secret-scan: allowlist-file
# Auto-generated by scripts/install-linux-timers.sh
[Unit]
Description=DuckBot daily decay prune (removes memories below retention floor)
[Service]
Type=oneshot
WorkingDirectory=$REPO_ROOT
ExecStart=$PYTHON_BIN -m src.cli decay --apply --retention-floor 0.05
StandardOutput=append:$LOG_DIR/decay.log
StandardError=append:$LOG_DIR/decay.err.log
EOF

cat > "$UNIT_DIR/duckbot-decay.timer" <<EOF
# duckbot-secret-scan: allowlist-file
# Auto-generated by scripts/install-linux-timers.sh
[Unit]
Description=Daily DuckBot decay prune at 03:00
[Timer]
OnCalendar=*-*-* 03:00:00
Persistent=true
[Install]
WantedBy=timers.target
EOF

# 3. Write the FSRS service + timer (Sundays at 04:00, self-tunes the
#    forgetting-curve exponent).
cat > "$UNIT_DIR/duckbot-fsrs.service" <<EOF
# duckbot-secret-scan: allowlist-file
# Auto-generated by scripts/install-linux-timers.sh
[Unit]
Description=DuckBot weekly FSRS forgetting-curve tuning
[Service]
Type=oneshot
WorkingDirectory=$REPO_ROOT
ExecStart=$PYTHON_BIN -m src.cli optimize-fsrs --apply
StandardOutput=append:$LOG_DIR/fsrs.log
StandardError=append:$LOG_DIR/fsrs.err.log
EOF

cat > "$UNIT_DIR/duckbot-fsrs.timer" <<EOF
# duckbot-secret-scan: allowlist-file
# Auto-generated by scripts/install-linux-timers.sh
[Unit]
Description=Weekly DuckBot FSRS tuning on Sundays at 04:00
[Timer]
OnCalendar=Sun *-*-* 04:00:00
Persistent=true
[Install]
WantedBy=timers.target
EOF

echo "✓ Wrote service + timer units under $UNIT_DIR"

# 4. Reload systemd, enable + start both timers so they fire on schedule.
systemctl --user daemon-reload
systemctl --user enable duckbot-decay.timer duckbot-fsrs.timer
echo "✓ Timers enabled"

# 5. Linger (so the timers survive logout). Requires sudo; one-time setup.
if command -v loginctl >/dev/null 2>&1; then
  if ! loginctl show-user "$USER" 2>/dev/null | grep -q 'Linger=yes'; then
    echo ""
    echo "⚠ To keep the timers running after logout, enable linger:"
    echo "    sudo loginctl enable-linger $USER"
    echo "  (one-time setup; requires sudo)"
  fi
fi

echo ""
echo "=== Timers installed and enabled ==="
echo ""
echo "Manage with:"
echo "  systemctl --user list-timers 'duckbot*'"
echo "  systemctl --user duckbot-decay.service        # run decay now"
echo "  systemctl --user duckbot-fsrs.service          # run FSRS tuning now"
echo "  journalctl --user -u duckbot-decay -f"
echo "  tail -f $LOG_DIR/decay.log"
